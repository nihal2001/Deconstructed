#!/usr/bin/env python3
"""Generates the standard ranking systems seed migration from the app's bundled JSON.

Deconstructed/Resources/StarterSystems.json is the single source of truth for the three
starter rubrics. Run this after editing it:

    python3 scripts/generate_seed.py

Note: published versions are immutable. To change a standard rubric after launch, add a new
version (new versionID and criterion IDs) in a new migration rather than regenerating this one.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Deconstructed" / "Resources" / "StarterSystems.json"
TARGET = ROOT / "supabase" / "migrations" / "20261007000004_seed_standard_systems.sql"


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def main() -> None:
    systems = json.loads(SOURCE.read_text())["systems"]
    out = [
        "-- Deconstructed: the three standard ranking systems.",
        "-- GENERATED by scripts/generate_seed.py from Deconstructed/Resources/StarterSystems.json.",
        "-- Do not edit by hand.",
        "",
        "begin;",
        "",
    ]
    for system in systems:
        total = sum(c["maxPoints"] for c in system["criteria"])
        assert total == 10, f"{system['name']} totals {total}, expected 10"
        sid, vid = system["id"].lower(), system["versionID"].lower()
        out += [
            f"-- {system['name']}",
            "insert into public.ranking_systems (id, owner_id, template_key, name, description)",
            f"values ('{sid}', null, {q(system['templateKey'])}, {q(system['name'])}, {q(system['summary'])});",
            "insert into public.ranking_system_versions (id, system_id, version_number)",
            f"values ('{vid}', '{sid}', 1);",
        ]
        for position, criterion in enumerate(system["criteria"]):
            levels = criterion["levels"]
            assert [l["points"] for l in levels] == list(range(criterion["maxPoints"] + 1)), criterion["name"]
            cid = criterion["id"].lower()
            out += [
                "insert into public.ranking_criteria (id, version_id, position, name, guidance, max_points)",
                f"values ('{cid}', '{vid}', {position}, {q(criterion['name'])}, {q(criterion['guidance'])}, {criterion['maxPoints']});",
                "insert into public.criterion_score_levels (criterion_id, points, label, description) values",
                ",\n".join(f"  ('{cid}', {l['points']}, {q(l['label'])}, {q(l['detail'])})" for l in levels) + ";",
            ]
        out += [f"update public.ranking_systems set current_version_id = '{vid}' where id = '{sid}';", ""]
    out += ["commit;", ""]
    TARGET.write_text("\n".join(out))
    print(f"Wrote {TARGET.relative_to(ROOT)} ({len(systems)} systems)")


if __name__ == "__main__":
    main()
